/*===========================================================================
  Clear WARELIB back to nothing, so 05_demo.sql can be re-run cleanly.

  Safe to run when a CRTPF or CRTDSPF has failed halfway and left a partial
  object behind. Touches nothing outside WARELIB.
===========================================================================*/
SET NOCOUNT ON;

DELETE QSYS.DSPF_FIELD
 WHERE FMTID IN (SELECT R.FMTID FROM QSYS.RECORD_FORMAT AS R
                 JOIN QSYS.OBJECT AS O ON O.OBJID = R.OBJID
                 WHERE O.LIBNAME = 'WARELIB');

DELETE QSYS.FIELD
 WHERE FMTID IN (SELECT R.FMTID FROM QSYS.RECORD_FORMAT AS R
                 JOIN QSYS.OBJECT AS O ON O.OBJID = R.OBJID
                 WHERE O.LIBNAME = 'WARELIB');

DELETE QSYS.RECORD_FORMAT
 WHERE OBJID IN (SELECT OBJID FROM QSYS.OBJECT WHERE LIBNAME = 'WARELIB');

DELETE QSYS.FILE_MEMBER
 WHERE OBJID IN (SELECT OBJID FROM QSYS.OBJECT WHERE LIBNAME = 'WARELIB');

DELETE QSYS.[FILE]
 WHERE OBJID IN (SELECT OBJID FROM QSYS.OBJECT WHERE LIBNAME = 'WARELIB');

DELETE QSYS.OBJECT  WHERE LIBNAME = 'WARELIB';
DELETE QSYS.SRC_MBR WHERE LIBNAME = 'WARELIB';
DELETE QSYS.LIBRARY WHERE LIBNAME = 'WARELIB';
GO

DROP PROCEDURE IF EXISTS WARELIB.INVENQ;
DROP TABLE     IF EXISTS WARELIB.PARTMST;
GO

PRINT 'WARELIB cleared. Re-run 05_demo.sql.';
GO
